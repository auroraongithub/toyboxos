PX.calendar = PX.plan;

const cache = new Map();
export const PAL = "0123456789abcdef";
export const rowsOf = g => (Array.isArray(g) ? g : g.r);
export const palOf = g => (Array.isArray(g) ? [] : g.p || []);
export const rects = g => {
  const p = palOf(g);
  let r = "";
  rowsOf(g).forEach((row, y) => {
    for (let x = 0; x < 16; ) {
      const c = row[x];
      let w = 1;
      while (row[x + w] === c) w++;
      const i = PAL.indexOf(c);
      if (i >= 0 && p[i]) r += `<rect fill="${p[i]}" x="${x}" y="${y}" width="${w}" height="1"/>`;
      else if (i < 0 && c !== "." && c) r += `<rect class="${c}" x="${x}" y="${y}" width="${w}" height="1"/>`;
      x += w;
    }
  });
  return r;
};
/* the Calendar tab draws like Plan until it gets a drawing of its own */
const ALIAS = { calendar: "plan" };
const own = id => pack.icons && pack.icons[id];
export const grid = id => own(id) || (ALIAS[id] && own(ALIAS[id])) || PX[id] || UX[id];
/* the pixel twin of line icon n for menus: an app's own drawing when the name is an app, else the interface set */
export const pxGrid = n => {
  const id = PX[n] ? n : LINE[n] || n;
  return grid(id) || UX[id];
};
setPixel(n => {
  const g = pxGrid(n);
  if (!g) return "";
  if (!cache.has(g)) cache.set(g, rects(g));
  return cache.get(g);
});
/* id = the app/part id; n = the line icon to fall back to when there's no pixel one */
export const AppIcon = ({ id, n }) => {
  const g = grid(id);
  if (!g) return n ? html`<${Icon} n=${n}/>` : null;
  if (!cache.has(g)) cache.set(g, rects(g));
  /* interface icons (uiicons.js) draw their outline in the text colour, like they do in menus */
  return html`<svg class=${"ic aic" + (UX[id] && !PX[id] ? " uxi" : "")} viewBox="0 0 16 16" aria-hidden="true" dangerouslySetInnerHTML=${{ __html: cache.get(g) }}/>`;
};
